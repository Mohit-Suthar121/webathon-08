export function generateRandomCrisisRequest(): ReliefRequest {
  const categories: ReliefRequest["category"][] = ["rescue", "medical", "water", "shelter", "food"];
  const areas = [
    { name: "Sanganer Lowland Basin", lat: 26.8150 + (Math.random() - 0.5) * 0.01, lng: 75.7720 + (Math.random() - 0.5) * 0.01 },
    { name: "Mansarovar Ward 14", lat: 26.8640 + (Math.random() - 0.5) * 0.01, lng: 75.7590 + (Math.random() - 0.5) * 0.01 },
    { name: "C-Scheme Central", lat: 26.9110 + (Math.random() - 0.5) * 0.01, lng: 75.8015 + (Math.random() - 0.5) * 0.01 },
    { name: "Amer Valley Ward 9", lat: 26.9855 + (Math.random() - 0.5) * 0.01, lng: 75.8510 + (Math.random() - 0.5) * 0.01 },
    { name: "Raja Park Block B", lat: 26.8995 + (Math.random() - 0.5) * 0.01, lng: 75.8290 + (Math.random() - 0.5) * 0.01 },
    { name: "Malviya Nagar Sector 3", lat: 26.8530 + (Math.random() - 0.5) * 0.01, lng: 75.8050 + (Math.random() - 0.5) * 0.01 },
    { name: "Bani Park Camp", lat: 26.9290 + (Math.random() - 0.5) * 0.01, lng: 75.7920 + (Math.random() - 0.5) * 0.01 },
  ];

  const sampleDescriptions: Record<ReliefRequest["category"], string[]> = {
    rescue: [
      "Flash flooding entered ground floor; 3 people perched on masonry wall.",
      "Senior citizen trapped inside bedroom with swollen door latch as water rises.",
      "Family stranded on top of car surrounded by 4ft swift water current.",
    ],
    medical: [
      "Severe asthma attack with power cut; emergency battery nebulizer needed.",
      "Fall injury with fracture; patient unable to move through flooded alley.",
      "Dialysis patient stranded by waterlogged street; needs transport urgently.",
    ],
    water: [
      "Contaminated tap supply; 8 households without safe drinking water.",
      "Water purifier flooded; urgent need for 20L sealed drinking jugs.",
      "Dehydration symptoms reported in flood shelter; clean water needed immediately.",
    ],
    shelter: [
      "Storm blew away asbestos roof; 5 family members soaking wet.",
      "Basement apartment submerged; family needs dry emergency shelter space.",
      "Need 2 waterproof heavy-duty tarpaulins to seal leaking ceiling.",
    ],
    food: [
      "No food or cooking gas for 24 hours; 6 children needing dry rations.",
      "Community shelter ran out of food packets for 15 displaced persons.",
      "Baby formula and biscuits urgently needed for 2 infants.",
    ],
  };

  const cat = categories[Math.floor(Math.random() * categories.length)];
  const area = areas[Math.floor(Math.random() * areas.length)];
  const descs = sampleDescriptions[cat];
  const desc = descs[Math.floor(Math.random() * descs.length)];
  const people = Math.floor(Math.random() * 8) + 1;
  const vulnerable = Math.random() > 0.45;
  const urgency = cat === "rescue" || cat === "medical" ? "critical" : Math.random() > 0.5 ? "high" : "medium";
  const now = Date.now();
  const id = `REQ-${Math.floor(1000 + Math.random() * 9000)}`;
  const phone = `+91 ${Math.floor(90000 + Math.random() * 9999)} ${Math.floor(10000 + Math.random() * 89999)}`;

  const { score } = calculateUrgencyScore(cat, people, vulnerable, now, now);

  return {
    id,
    category: cat,
    description: desc,
    peopleAffected: people,
    vulnerable,
    urgency,
    areaName: area.name,
    lat: area.lat,
    lng: area.lng,
    contactPhone: phone,
    status: "open",
    createdAt: now,
    urgencyScore: score,
    verified: false,
  };
}
